#!/usr/bin/env python3
"""Turns tools/guls/flag_guls.json into lib/features/puzzles/gol_charts.dart.

The five guls of the Turkmen flag, one per puzzle level (Teke, Yomut, Arsary,
Cowdur, Saryk), as charts of knots. Run from the project root:

    python3 tools/guls/make_gol_charts.py

Leftover bits of the flag's side border (yellow or dark pieces that touch the
edge of a chart and are not part of the gul) are removed. The side border of
the strip is written too, as one repeat that tiles top to bottom.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "tools/guls/flag_guls.json"
TARGET = ROOT / "lib/features/puzzles/gol_charts.dart"

# Flag order, top to bottom, is the order of the levels, bottom to top.
KINDS = ["teke", "yomut", "arsary", "cowdur", "saryk"]
# A stray piece of the strip's border is yellow or dark, cut off from the gul,
# touches the edge of the chart and is small next to the gul.
MAX_STRAY = 150


def components(grid):
    rows, cols = len(grid), len(grid[0])
    seen = [[False] * cols for _ in range(rows)]
    found = []
    for r in range(rows):
        for c in range(cols):
            if grid[r][c] == "." or seen[r][c]:
                continue
            cells, stack = [], [(r, c)]
            seen[r][c] = True
            while stack:
                a, b = stack.pop()
                cells.append((a, b))
                for da in (-1, 0, 1):
                    for db in (-1, 0, 1):
                        x, y = a + da, b + db
                        if 0 <= x < rows and 0 <= y < cols and not seen[x][y] and grid[x][y] != ".":
                            seen[x][y] = True
                            stack.append((x, y))
            found.append(cells)
    return sorted(found, key=len, reverse=True)


def clean(rows):
    grid = [list(r) for r in rows]
    rows, cols = len(grid), len(grid[0])
    for cells in components(grid)[1:]:
        letters = {grid[a][b] for a, b in cells}
        at_edge = any(a in (0, rows - 1) or b in (0, cols - 1) for a, b in cells)
        if len(cells) < MAX_STRAY and letters <= {"y", "k"} and at_edge:
            for a, b in cells:
                grid[a][b] = "."
    rows = ["".join(r) for r in grid]
    # Cleaning can leave empty rows at the ends; trim them so the gul stays
    # centred in its chart.
    while rows and set(rows[0]) == {"."}:
        rows.pop(0)
    while rows and set(rows[-1]) == {"."}:
        rows.pop()
    # An odd number of rows keeps a middle row. A blank row at the bottom
    # does not move the centre of the gul.
    if len(rows) % 2 == 0:
        rows.append("." * len(rows[0]))
    return rows


def main():
    data = json.loads(SOURCE.read_text())
    lines = [
        "// GENERATED by tools/guls/make_gol_charts.py from tools/guls/flag_guls.json.",
        "// Do not edit by hand; change the source and run the script again.",
        "//",
        "// The five guls of the Turkmen flag, one chart per level. One character is",
        "// one knot: . none, r red, y yellow, w white, g green, k dark.",
        "",
        "const Map<String, List<String>> kGolChartRows = {",
    ]
    for kind, key in zip(KINDS, ["gul1", "gul2", "gul3", "gul4", "gul5"]):
        rows = clean(data[key])
        assert len({len(r) for r in rows}) == 1, key
        assert len(rows) % 2 == 1, key
        lines.append(f"  '{kind}': [")
        lines += [f"    '{r}'," for r in rows]
        lines.append("  ],")
    lines.append("};")
    border = data["border"]
    assert len({len(r) for r in border}) == 1
    lines += [
        "",
        "/// One repeat of the strip's side border; it tiles from top to bottom.",
        "const List<String> kBorderRows = [",
    ]
    lines += [f"  '{r}'," for r in border]
    lines.append("];")
    TARGET.write_text("\n".join(lines) + "\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
